/* <endian.h> for Windows (only added to the include path on Windows).  Windows
 * on x86, x64 and ARM64 is always little endian.
 */

#ifndef WPARTED_WIN32COMPAT_ENDIAN_H
#define WPARTED_WIN32COMPAT_ENDIAN_H

#include <stdlib.h>

#define htobe16(x) _byteswap_ushort(x)
#define htole16(x) (x)
#define be16toh(x) _byteswap_ushort(x)
#define le16toh(x) (x)
#define htobe32(x) _byteswap_ulong(x)
#define htole32(x) (x)
#define be32toh(x) _byteswap_ulong(x)
#define le32toh(x) (x)
#define htobe64(x) _byteswap_uint64(x)
#define htole64(x) (x)
#define be64toh(x) _byteswap_uint64(x)
#define le64toh(x) (x)

#endif /* WPARTED_WIN32COMPAT_ENDIAN_H */
